/**
 * Writes `packages/player-web/src/fonts-data.ts` from `native/src/fonts_data.h`: the built-in font sheets libtse makes for a "tse:"
 * texture name, one bit a pixel, for the browser backend, which has no libtse to ask. Run it after `tools/fonts/make-fonts.py`
 * changes the header; `packages/player-web/test/fonts.test.ts` fails while the two differ.
 *
 *   node tools/make-web-fonts.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Each font in the header: its name, its cell, and its sheet's bits. */
export function parseFontHeader(header: string): { name: string; cellWidth: number; cellHeight: number; bits: Uint8Array }[] {
  const arrays = new Map<string, Uint8Array>();
  for (const m of header.matchAll(/static const unsigned char (\w+)\[(\d+)\] = \{([^}]*)\};/g)) {
    const bytes = [...m[3]!.matchAll(/0x([0-9a-fA-F]{2})/g)].map((b) => parseInt(b[1]!, 16));
    if (bytes.length !== Number(m[2])) throw new Error(`${m[1]}: ${bytes.length} bytes, the header says ${m[2]}`);
    arrays.set(m[1]!, Uint8Array.from(bytes));
  }
  const table = /BUILTIN_FONTS\[\] = \{([^;]*)\};/.exec(header);
  if (table === null) throw new Error("no BUILTIN_FONTS table in the header");
  return [...table[1]!.matchAll(/\{ "([^"]+)", (\d+), (\d+), (\w+) \}/g)].map((m) => {
    const bits = arrays.get(m[4]!);
    if (bits === undefined) throw new Error(`${m[1]}: no array ${m[4]}`);
    return { name: m[1]!, cellWidth: Number(m[2]), cellHeight: Number(m[3]), bits };
  });
}

/** The TypeScript module for those fonts. */
export function webFontsModule(header: string): string {
  const fonts = parseFontHeader(header);
  const lines = fonts.map(
    (f) =>
      `  ${JSON.stringify(f.name)}: { cellWidth: ${f.cellWidth}, cellHeight: ${f.cellHeight}, bits: ${JSON.stringify(Buffer.from(f.bits).toString("base64"))} },`
  );
  return `// Generated by tools/make-web-fonts.ts from native/src/fonts_data.h: do not edit. Where each font comes from and its license:
// tools/fonts/README.md.

/**
 * The fonts built into libtse, for the browser: each a sheet of the characters 32 to 127 in 16 columns and 6 rows of cells, one bit
 * a pixel (base64), rows top first, the left pixel in a byte's top bit, each row starting on a byte.
 */
export const BUILTIN_FONT_BITS: Readonly<Record<string, { readonly cellWidth: number; readonly cellHeight: number; readonly bits: string }>> = {
${lines.join("\n")}
};
`;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const header = readFileSync(join(root, "native/src/fonts_data.h"), "utf8");
  const out = join(root, "packages/player-web/src/fonts-data.ts");
  writeFileSync(out, webFontsModule(header));
  console.log(`wrote ${out}`);
}
