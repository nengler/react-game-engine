#define SMALL_CELL_W 4
#define SMALL_CELL_H 6

bool builtin_font_image(const char *name, Image *out) {
  if (name == NULL || strcmp(name, "tse:small") != 0) return false;
  int width = 16 * SMALL_CELL_W, height = 6 * SMALL_CELL_H;
  Image image = GenImageColor(width, height, BLANK);
  ImageFormat(&image, PIXELFORMAT_UNCOMPRESSED_R8G8B8A8);
  unsigned char *pixels = image.data;
  for (int code = 0; code < 96; code++) {
    int cx = (code % 16) * SMALL_CELL_W, cy = (code / 16) * SMALL_CELL_H;
    for (int y = 0; y < SMALL_CELL_H; y++) {
      unsigned char bits = SMALL[code * 6 + y];
      for (int x = 0; x < 3; x++) {
        if (!(bits & (1 << (2 - x)))) continue;
        unsigned char *p = pixels + ((cy + y) * width + cx + x) * 4;
        p[0] = p[1] = p[2] = p[3] = 255;
      }
    }
  }
  *out = image;
  return true;
}
