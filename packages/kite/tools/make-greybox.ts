/**
 * Writes `src/Level.tsx`: every room drawn as boxes (`<Shape>`s), for the first draft of the movement, before the
 * tile sheet and the Tiled maps exist. Solid tiles are merged into runs along each row.
 *
 *   node packages/kite/tools/make-greybox.ts
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { TILE } from "../src/rules/constants.ts";
import { hazardRect, ROOM_LIST } from "../src/rules/rooms.ts";

const out: string[] = [];
for (const room of ROOM_LIST) {
  out.push(`      {/* ${room.index + 1}. ${room.name} */}`);
  out.push(`      <Entity name="Room${room.index + 1}" transform={{ x: ${room.ox}, y: ${room.oy} }}>`);
  room.rows.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      const ch = row[c] as string;
      if (ch === "#") {
        let end = c;
        while (row[end + 1] === "#") end++;
        out.push(`        <Shape kind="rect" width={${(end - c + 1) * TILE}} height={${TILE}} color="#3b4666" transform={{ x: ${c * TILE}, y: ${r * TILE} }} />`);
        c = end;
      } else {
        const rect = hazardRect(ch, c, r);
        if (rect !== null) out.push(`        <Shape kind="rect" width={${rect.w}} height={${rect.h}} color="#d9435a" transform={{ x: ${rect.x}, y: ${rect.y} }} />`);
      }
    }
  });
  out.push("      </Entity>");
}
const source = `import { Entity, Shape } from "@rge/runtime/jsx";

// Generated by tools/make-greybox.ts from rules/rooms.ts. Do not edit.

/** Every room, side by side where the world puts them: solid tiles and spikes as boxes. */
export function Level() {
  return (
    <Entity name="Level">
${out.join("\n")}
    </Entity>
  );
}
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../src/Level.tsx"), source);
console.log(`wrote Level.tsx (${out.length} lines)`);
