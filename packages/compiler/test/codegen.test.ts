import assert from "node:assert/strict";
import { after, describe, it } from "node:test";

import { DiagnosticCode, formatDiagnostic } from "../src/index.ts";
import { cleanOutput, closeCompiler, compile, typeCheck } from "./helpers.ts";

after(() => {
  closeCompiler();
  cleanOutput();
});

const PLAYER = `
function Player() {
  const s = useMutable({ health: 100 });
  return (
    <Entity>
      <Sprite image="player.png" />
      {s.health < 25 && <WarningIcon />}
    </Entity>
  );
}

function WarningIcon() {
  return <Entity name="Warning" />;
}
`;

describe("code generation", () => {
  it("generates the expected class for the reference component", () => {
    const { code } = compile(PLAYER, "Player.tsx");
    assert.equal(
      code,
      `// Generated by @tsengine/compiler from Player.tsx. Do not edit.
import { Entity, Sprite } from "@tsengine/runtime";

export class Player extends Entity {
  static readonly managed = true;
  protected override readonly reportsChanges = true;
  $s_health: number = 100;
  #$s_healthNext: number = this.$s_health;
  #sView: { health: number } | undefined;
  get s(): { health: number } { const self = this; return (this.#sView ??= { get health() { return self.$s_health; }, set health(value: number) { self.$set_s_health(value); } }); }
  readonly sprite: Sprite = new Sprite({ image: "player.png" });
  warningIcon: WarningIcon | null = null;

  constructor() {
    super({ name: "Player" });
    this.addChild(this.sprite, 0);
    this.render();
    this.commitStructure();
  }

  $set_s_health(value: number): void {
    if (value === this.#$s_healthNext) return;
    this.#$s_healthNext = value;
    this.markDirty();
  }

  override commitState(): void {
    this.$s_health = this.#$s_healthNext;
  }

  override saveHotState(): Record<string, unknown> {
    return { "Player.s.health": this.#$s_healthNext };
  }

  override loadHotState(saved: Record<string, unknown>): void {
    let value: unknown;
    value = saved["Player.s.health"];
    if (this.hotFits(value, this.#$s_healthNext)) this.#$s_healthNext = value as number;
    this.markDirty();
  }

  override render(): void {
    if (this.$s_health < 25) {
      if (this.warningIcon === null) {
        this.warningIcon = new WarningIcon();
        this.queueAddChild(this.warningIcon, 1);
      }
    } else if (this.warningIcon !== null) {
      this.queueRemoveChild(this.warningIcon);
      this.warningIcon = null;
    }
  }
}

export class WarningIcon extends Entity {
  static readonly managed = true;
  protected override readonly reportsChanges = true;

  constructor() {
    super({ name: "Warning" });
  }
}
`
    );
  });

  it("turns static children into persistent readonly fields", () => {
    const { code } = compile(`
      function P() {
        return (
          <Entity>
            <Sprite image="a.png" />
            <Collider width={16} height={24} />
          </Entity>
        );
      }
    `);
    assert.match(code, /^ {2}readonly sprite: Sprite = new Sprite\(\{ image: "a\.png" \}\);$/m);
    assert.match(code, /^ {2}readonly collider: Collider = new Collider\(\{ width: 16, height: 24 \}\);$/m);
    // Nothing is dynamic, so there is no render pass at all.
    assert.doesNotMatch(code, /render\(\)/);
  });

  it("turns each field into a typed instance field with a setter", () => {
    const { code } = compile(`
      function P() {
        const s = useMutable({ health: 100, label: "idle", alive: true });
        return <Entity name={s.label} />;
      }
    `);
    assert.match(code, /^ {2}\$s_health: number = 100;$/m);
    assert.match(code, /^ {2}\$s_label: string = "idle";$/m);
    assert.match(code, /^ {2}\$s_alive: boolean = true;$/m);
    assert.match(code, /\$set_s_health\(value: number\): void/);
    assert.match(code, /\$set_s_label\(value: string\): void/);
    assert.match(code, /\$set_s_alive\(value: boolean\): void/, "every field can be written");
  });

  it("updates dynamic props by assigning to the existing instance", () => {
    const { code } = compile(`
      function P() {
        const s = useMutable({ health: 100 });
        return <Entity><Sprite image={s.health > 50 ? "normal.png" : "hurt.png"} /></Entity>;
      }
    `);
    // Written only when it differs, and then the sprite is told: a render that changes nothing reports nothing.
    assert.match(
      code,
      /override render\(\): void \{\n {4}const \$1: Sprite\["image"\] = \(this\.\$s_health > 50\) \? "normal\.png" : "hurt\.png";\n {4}if \(this\.sprite\.image !== \$1\) \{\n {6}this\.sprite\.image = \$1;\n {6}this\.sprite\.markChanged\(\);\n {4}\}\n {2}\}/
    );
    // The sprite is only ever constructed in its field initialiser.
    assert.equal(code.match(/new Sprite/g)?.length, 1);
  });

  it("parenthesises expressions so precedence is preserved", () => {
    const { code } = compile(`
      function P() {
        const s = useMutable({ a: 1, b: 2 });
        return <Entity><Collider width={(s.a + s.b) * 2} height={s.a + s.b * 2} /></Entity>;
      }
    `);
    assert.match(code, /const (\$\d+)(?:: [^=]+)? = \(this\.\$s_a \+ this\.\$s_b\) \* 2;[^]*?this\.collider\.width = \1;/);
    assert.match(code, /const (\$\d+)(?:: [^=]+)? = this\.\$s_a \+ \(this\.\$s_b \* 2\);[^]*?this\.collider\.height = \1;/);
  });
});

describe("type-checking generated code", () => {
  it("carries a null check on a derived value into a child's props, under more than one condition", () => {
    // `chosen` is worked out by a call, so each read is a call TypeScript cannot narrow from one to the next: a child's prop
    // getter reads it once into a local, tests the local and returns it.
    const compiled = compile(`
      function Card({ item }: { item: { name: string } }) {
        return <Text>{item.name}</Text>;
      }
      function Board() {
        const s = useMutable({ items: [{ name: "a" }], at: 0 });
        const chosen = s.items.find((i) => i.name === "a") ?? null;
        return (
          <Entity>
            {chosen !== null && s.at === 0 && <Card item={chosen} />}
            {chosen !== null && chosen.name === "a" && <Card item={chosen} />}
          </Entity>
        );
      }
    `);
    assert.deepEqual(typeCheck(compiled), []);
  });

  it("type-checks an element with a changing prop that follows an optional chain in a condition", () => {
    // TypeScript 7.1 (beta) cannot find `this` in a `typeof this.x` type once an optional chain has been a condition earlier in
    // the method, so a changing prop's local is typed through the built-in's class instead (`Text["text"]`).
    const compiled = compile(`
      function Board({ lesson }: { lesson: { target: string } | null }) {
        const s = useMutable({ score: 0 });
        return (
          <Entity>
            {lesson?.target === "jar" && <Shape kind="rect" width={8} height={8} />}
            {s.score >= 0 && <Text>{\`\${s.score}\`}</Text>}
            <Shape kind="rect" width={s.score} height={2} />
          </Entity>
        );
      }
    `);
    assert.doesNotMatch(compiled.code, /typeof this\./);
    assert.deepEqual(typeCheck(compiled), []);
  });

  it("generated TypeScript compiles and type-checks", () => {
    const compiled = compile(`
      function Player() {
        const s = useMutable({ health: 100, visible: true });
        return (
          <Entity name="Player">
            <Sprite image={s.health > 50 ? "normal.png" : "hurt.png"} />
            <Collider width={16} height={24} />
            {s.health < 25 && <WarningIcon />}
            {s.visible && (
              <Entity name="Shield">
                <Sprite image={s.health > 10 ? "shield.png" : "shield-cracked.png"} />
                {s.health < 5 && <Collider width={s.health} height={2} />}
              </Entity>
            )}
          </Entity>
        );
      }
      function WarningIcon() {
        return <Entity><Sprite image="warning.png" /></Entity>;
      }
    `);
    const diagnostics = typeCheck(compiled);
    assert.deepEqual(diagnostics.map(formatDiagnostic), []);
  });

  it("reports type errors in generated code (the check is real)", () => {
    // The compiler does not know intrinsic prop types; the type checker does.
    const compiled = compile(`
      function P() {
        return <Entity><Sprite image={5} /></Entity>;
      }
    `);
    const diagnostics = typeCheck(compiled);
    assert.equal(diagnostics.length, 1);
    assert.equal(diagnostics[0]!.code, DiagnosticCode.GeneratedTypeError);
    assert.match(diagnostics[0]!.message, /^TS2322: Type 'number' is not assignable to type 'string'/);
  });

  it("reports missing required intrinsic props", () => {
    const compiled = compile(`function P() { return <Entity><Collider width={1} /></Entity>; }`);
    const messages = typeCheck(compiled).map((d) => d.message);
    assert.ok(
      messages.some((m) => m.includes("'height'")),
      messages.join("\n")
    );
  });
});
