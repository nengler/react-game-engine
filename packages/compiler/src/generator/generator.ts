import {
  assertNever,
  type ChildIR,
  type ComponentIR,
  type ComponentRef,
  type ElementIR,
  type ExprIR,
  type IRModule,
  type PropIR,
  type StateId,
  type StateIR,
} from "../ir/types.ts";
import { CodeWriter } from "./writer.ts";

export interface GeneratorOptions {
  /** Module specifier the generated code imports runtime classes from. */
  readonly runtimeModule: string;
}

/**
 * IR → TypeScript. Emits one class per component:
 *
 * - state            → typed instance fields
 * - static children  → `readonly` fields, constructed once and attached in the constructor
 * - conditional      → nullable fields, created/destroyed in `render()` via queued structure ops
 * - dynamic props    → assignments to the existing child instance in `render()`
 * - setters          → update the field and `markDirty()`
 */
export function generateModule(module: IRModule, options: GeneratorOptions): string {
  const w = new CodeWriter();
  w.line(`// Generated by @rge/compiler from ${module.sourceFile}. Do not edit.`);

  const intrinsics = collectIntrinsics(module);
  if (intrinsics.length > 0) {
    w.line(`import { ${intrinsics.join(", ")} } from ${JSON.stringify(options.runtimeModule)};`);
  }
  for (const component of module.components) {
    w.blank();
    new ComponentGenerator(component, w).emit();
  }
  return w.toString();
}

function collectIntrinsics(module: IRModule): string[] {
  const names = new Set<string>();
  const visit = (children: readonly ChildIR[]): void => {
    for (const child of children) {
      if (child.element.component.kind === "Intrinsic") names.add(child.element.component.name);
      visit(child.element.children);
    }
  };
  for (const c of module.components) {
    names.add(c.root.component.name);
    visit(c.root.children);
  }
  return [...names].sort();
}

/** Where an element lives: always present (readonly), or only while an enclosing condition holds. */
type Presence = "persistent" | "conditional";

class ComponentGenerator {
  readonly #c: ComponentIR;
  readonly #w: CodeWriter;
  readonly #stateById: ReadonlyMap<StateId, StateIR>;

  constructor(component: ComponentIR, writer: CodeWriter) {
    this.#c = component;
    this.#w = writer;
    this.#stateById = new Map(component.state.map((s) => [s.id, s]));
  }

  emit(): void {
    const c = this.#c;
    const w = this.#w;
    const hasRender = this.#hostHasDynamicProps() || this.#childrenNeedRender(c.root.children);

    w.block(`export class ${c.name} extends ${c.root.component.name}`, () => {
      // Persistent state.
      for (const s of c.state) {
        w.line(`${s.name}: ${s.type} = ${this.#expr(s.initialValue, true)};`);
      }
      // Persistent children (field initialisers run after state initialisers, so they can read state).
      this.#emitElementFields(c.root.children, "persistent");

      w.blank();
      w.block("constructor()", () => {
        const staticHostProps = c.root.props.filter((p) => p.kind === "StaticProp");
        w.line(staticHostProps.length > 0 ? `super(${this.#propsObject(staticHostProps)});` : "super();");
        this.#emitStaticWiring(c.root.children, "this");
        if (hasRender) {
          w.line("this.render();");
          w.line("this.commitStructure();");
        }
      });

      for (const hook of c.hooks) {
        switch (hook.kind) {
          case "UseState": {
            if (hook.setterName === null) break;
            const s = this.#state(hook.state);
            w.blank();
            w.block(`${hook.setterName}(value: ${s.type} | ((previous: ${s.type}) => ${s.type})): void`, () => {
              w.line(`const next = typeof value === "function" ? value(this.${s.name}) : value;`);
              w.line(`if (next === this.${s.name}) return;`);
              w.line(`this.${s.name} = next;`);
              w.line("this.markDirty();");
            });
            break;
          }
          default:
            assertNever(hook.kind, "hook");
        }
      }

      if (hasRender) {
        w.blank();
        w.block("override render(): void", () => {
          for (const prop of c.root.props) {
            if (prop.kind === "DynamicProp") w.line(`${access("this", prop.name)} = ${this.#expr(prop.value, true)};`);
          }
          this.#emitChildUpdates(c.root.children, "this", "persistent");
        });
      }
    });
  }

  // -- fields ---------------------------------------------------------------

  #emitElementFields(children: readonly ChildIR[], presence: Presence): void {
    for (const child of children) {
      const el = child.element;
      const type = typeName(el.component);
      const childPresence: Presence = child.kind === "ConditionalChild" ? "conditional" : presence;
      if (childPresence === "persistent") {
        this.#w.line(`readonly ${el.fieldName}: ${type} = ${this.#construct(el)};`);
      } else {
        this.#w.line(`${el.fieldName}: ${type} | null = null;`);
      }
      this.#emitElementFields(el.children, childPresence);
    }
  }

  /** Attach persistent children to their parents (constructor only). */
  #emitStaticWiring(children: readonly ChildIR[], parentRef: string): void {
    for (const child of children) {
      if (child.kind !== "StaticChild") continue;
      const ref = `this.${child.element.fieldName}`;
      this.#w.line(`${parentRef}.addChild(${ref});`);
      this.#emitStaticWiring(child.element.children, ref);
    }
  }

  // -- render ---------------------------------------------------------------

  #emitChildUpdates(children: readonly ChildIR[], parentRef: string, presence: Presence): void {
    const w = this.#w;
    for (const child of children) {
      switch (child.kind) {
        case "StaticChild": {
          const el = child.element;
          if (!this.#elementNeedsRender(el)) break;
          const ref = `this.${el.fieldName}`;
          if (presence === "persistent") {
            this.#emitElementUpdates(el, ref, "persistent");
          } else {
            // Inside a conditional subtree the field may be null (e.g. the subtree is unmounted).
            w.block(`if (${ref} !== null)`, () => this.#emitElementUpdates(el, ref, "conditional"));
          }
          break;
        }
        case "ConditionalChild": {
          const el = child.element;
          const ref = `this.${el.fieldName}`;
          w.open(`if (${this.#expr(child.condition, true)}) {`);
          w.block(`if (${ref} === null)`, () => {
            w.line(`${ref} = ${this.#construct(el)};`);
            this.#emitMountStatics(el.children, ref);
            w.line(`${parentRef}.queueAddChild(${ref});`);
          });
          this.#emitElementUpdates(el, ref, "conditional");
          w.close();
          w.open(`} else if (${ref} !== null) {`);
          w.line(`${parentRef}.queueRemoveChild(${ref});`);
          for (const field of subtreeFields(el)) w.line(`this.${field} = null;`);
          w.close("}");
          break;
        }
        default:
          assertNever(child, "child");
      }
    }
  }

  #emitElementUpdates(el: ElementIR, ref: string, presence: Presence): void {
    for (const prop of el.props) {
      if (prop.kind === "DynamicProp") this.#w.line(`${access(ref, prop.name)} = ${this.#expr(prop.value, true)};`);
    }
    this.#emitChildUpdates(el.children, ref, presence);
  }

  /** When a conditional subtree mounts, construct its static descendants and attach them immediately. */
  #emitMountStatics(children: readonly ChildIR[], parentRef: string): void {
    for (const child of children) {
      if (child.kind !== "StaticChild") continue;
      const ref = `this.${child.element.fieldName}`;
      this.#w.line(`${ref} = ${this.#construct(child.element)};`);
      this.#w.line(`${parentRef}.addChild(${ref});`);
      this.#emitMountStatics(child.element.children, ref);
    }
  }

  #hostHasDynamicProps(): boolean {
    return this.#c.root.props.some((p) => p.kind === "DynamicProp");
  }

  #elementNeedsRender(el: ElementIR): boolean {
    return el.props.some((p) => p.kind === "DynamicProp") || this.#childrenNeedRender(el.children);
  }

  #childrenNeedRender(children: readonly ChildIR[]): boolean {
    return children.some((c) => c.kind === "ConditionalChild" || this.#elementNeedsRender(c.element));
  }

  // -- expressions ----------------------------------------------------------

  #construct(el: ElementIR): string {
    switch (el.component.kind) {
      case "Local":
        return `new ${el.component.name}()`;
      case "Intrinsic":
        return el.props.length > 0 ? `new ${el.component.name}(${this.#propsObject(el.props)})` : `new ${el.component.name}()`;
      default:
        return assertNever(el.component, "component ref");
    }
  }

  #propsObject(props: readonly PropIR[]): string {
    return `{ ${props.map((p) => `${propertyKey(p.name)}: ${this.#expr(p.value, true)}`).join(", ")} }`;
  }

  #state(id: StateId): StateIR {
    const s = this.#stateById.get(id);
    if (!s) throw new Error(`Unknown state ${id} in component ${this.#c.name}`);
    return s;
  }

  /** Compound sub-expressions are always parenthesised, so operator precedence can never be wrong. */
  #expr(e: ExprIR, top = false): string {
    const wrap = (s: string): string => (top ? s : `(${s})`);
    switch (e.kind) {
      case "NumberLiteral": return String(e.value);
      case "StringLiteral": return JSON.stringify(e.value);
      case "BooleanLiteral": return String(e.value);
      case "NullLiteral": return "null";
      case "StateRead": return `this.${this.#state(e.state).name}`;
      case "Unary": return wrap(`${e.operator}${this.#expr(e.operand)}`);
      case "Binary": return wrap(`${this.#expr(e.left)} ${e.operator} ${this.#expr(e.right)}`);
      case "Conditional": return wrap(`${this.#expr(e.test)} ? ${this.#expr(e.whenTrue)} : ${this.#expr(e.whenFalse)}`);
      default: return assertNever(e, "expression");
    }
  }
}

function typeName(ref: ComponentRef): string {
  return ref.name;
}

/** Field names of an element and all its descendants (every one of them lives and dies with it). */
function subtreeFields(el: ElementIR): string[] {
  return [el.fieldName, ...el.children.flatMap((c) => subtreeFields(c.element))];
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function propertyKey(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

function access(target: string, name: string): string {
  return IDENTIFIER.test(name) ? `${target}.${name}` : `${target}[${JSON.stringify(name)}]`;
}
