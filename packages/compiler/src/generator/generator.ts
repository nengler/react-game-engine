import { assertNever, type ChildIR, type ExprIR, type IRModule, type PropIR, type FunctionIR, isHandlerHook, type TypeIR, walkExpr, walkFunction } from "../ir/types.ts";
import { exportedComponents, moduleSchemas } from "../prefabs/prefabs.ts";
import { CodeWriter } from "./writer.ts";
import { ROOT, findChildrenSlot, typeText, pending, pendingRef, propertyKey, access } from "./helpers.ts";
import { ElementEmitter } from "./elements.ts";



export interface GeneratorOptions {
  /** Module specifier the generated code imports runtime classes from. */
  readonly runtimeModule: string;
  /** Runtime functions handler code may call (imported from `runtimeModule`). */
  readonly runtimeFunctions: ReadonlySet<string>;
  /** Props each built-in's constructor requires (the runtime manifest's `intrinsicRequired`). */
  readonly requiredHostProps: Readonly<Record<string, readonly string[]>>;
  /** Hooks each built-in implements itself (the runtime manifest's `intrinsicHooks`): a component rooted at one calls `super` first. */
  readonly intrinsicHooks: Readonly<Record<string, readonly string[]>>;
  /**
   * The project's game state, for a module whose components read or act on it: the exported name and where to import it
   * from (relative to the generated file).
   */
  readonly gameState?: { readonly name: string; readonly importFrom: string };
  /** The path from the generated files to the source folder, so `./transitions.ts` becomes `../src/transitions.ts`. Default `".."` + `/`: see `Compiler`. */
  readonly sourceFromOutput?: string;
  /** The generated `tilemaps.ts`, imported for its registration by a module that draws a `<Tilemap>` (see `Compiler.setTilemapsModule`). */
  readonly tilemapsModule?: string;
}

/**
 * IR → TypeScript. Emits one class per component:
 *
 * - state            → typed instance fields
 * - static children  → `readonly` fields, constructed once and attached in the constructor
 * - conditional      → nullable fields, created/destroyed in `render()` via queued structure ops
 * - dynamic props    → assignments to the existing child instance in `render()`
 * - setters          → update the field and `markDirty()`
 */
export function generateModule(module: IRModule, options: GeneratorOptions): string {
  const w = new CodeWriter();
  w.line(`// Generated by @rge/compiler from ${module.sourceFile}. Do not edit.`);

  const usage = { store: false, plain: new Set<string>() };
  const imports = collectImports(module, options.runtimeFunctions, usage, options.intrinsicHooks);
  // What the file's own constants and helpers read: a function from a `.ts` file, a runtime function.
  for (const declaration of module.moduleDeclarations) {
    for (const name of declaration.reads) {
      if (module.plainImports.some((i) => i.name === name)) usage.plain.add(name);
      if (options.runtimeFunctions.has(name) && !imports.includes(name)) imports.push(name);
    }
  }
  if (imports.length > 0) {
    w.line(`import { ${imports.join(", ")} } from ${JSON.stringify(options.runtimeModule)};`);
  }
  if (options.tilemapsModule !== undefined && imports.includes("Tilemap")) w.line(`import ${JSON.stringify(options.tilemapsModule)};`);
  if (usage.store) {
    if (!options.gameState) throw new Error("A component uses the game state, but the generator was given none.");
    w.line(`import { ${options.gameState.name} } from ${JSON.stringify(options.gameState.importFrom)};`);
  }
  const byModule = new Map<string, string[]>();
  for (const i of module.plainImports) if (usage.plain.has(i.name)) (byModule.get(i.module) ?? byModule.set(i.module, []).get(i.module)!).push(i.name);
  for (const [specifier, names] of byModule) {
    const from = options.sourceFromOutput ?? "..";
    w.line(`import { ${names.join(", ")} } from ${JSON.stringify(`${from}/${specifier.replace(/^\.\//, "")}`)};`);
  }
  // Types from .ts files (a props type may name one) are imported as types once the rest is written, those it mentions only.
  const typesAt = w.toString().length;
  for (const [specifier, { defaultName, names }] of collectComponentImports(module)) {
    const clause = [defaultName, names.length > 0 ? `{ ${names.join(", ")} }` : null].filter((part) => part !== null).join(", ");
    w.line(`import ${clause} from ${JSON.stringify(specifier)};`);
  }
  for (const declaration of module.typeDeclarations) {
    w.blank();
    w.line(`export ${declaration.text}`);
  }
  for (const declaration of module.moduleDeclarations) {
    w.blank();
    for (const line of declaration.text.split("\n")) w.line(line);
  }
  for (const component of module.components) {
    w.blank();
    new ComponentGenerator(component, w, options.requiredHostProps, options.intrinsicHooks, options.gameState?.name ?? "").emit();
    if (component.isDefaultExport) {
      w.blank();
      w.line(`export default ${component.name};`);
    }
  }
  emitPrefabs(module, w);
  const text = w.toString();
  const body = text.slice(typesAt);
  const typesByModule = new Map<string, string[]>();
  for (const i of module.typeImports) {
    if (!new RegExp(`\\b${i.name}\\b`).test(body)) continue;
    (typesByModule.get(i.module) ?? typesByModule.set(i.module, []).get(i.module)!).push(i.importedName !== undefined ? `${i.importedName} as ${i.name}` : i.name);
  }
  const from = options.sourceFromOutput ?? "..";
  const lines = [...typesByModule].map(([specifier, names]) => `import type { ${names.join(", ")} } from ${JSON.stringify(`${from}/${specifier.replace(/^\.\//, "")}`)};\n`).join("");
  return text.slice(0, typesAt) + lines + body;
}

/**
 * `export const prefabs = { Enemy: { create, props } }` for the exported
 * components: the data a scene needs to place them. `ConstructorParameters`
 * types `create`, so the props interface need not be exported.
 */
function emitPrefabs(module: IRModule, w: CodeWriter): void {
  const exported = exportedComponents(module);
  if (exported.length === 0) return;
  const schemas = new Map(moduleSchemas(module).map((s) => [s.name, s] as const));
  w.blank();
  w.open("export const prefabs = {");
  for (const component of exported) {
    w.open(`${component.name}: {`);
    w.line(
      component.propsType
        ? `create: (props: ConstructorParameters<typeof ${component.name}>[0]) => new ${component.name}(props),`
        : `create: () => new ${component.name}(),`,
    );
    const props = schemas.get(component.name)!.props;
    if (props.length === 0) w.line("props: [],");
    else {
      w.open("props: [");
      for (const prop of props) w.line(`${JSON.stringify(prop)},`);
      w.close("],");
    }
    w.close("},");
  }
  w.close("} satisfies Record<string, PrefabDefinition>;");
}

/** Runtime values (intrinsic classes, helper functions) and types the module's output refers to. */
function collectImports(module: IRModule, runtimeFunctions: ReadonlySet<string>, usage: { store: boolean; plain: Set<string> }, intrinsicHooks: Readonly<Record<string, readonly string[]>> | undefined): string[] {
  const values = new Set<string>();
  const types = new Set<string>();
  const visitType = (type: TypeIR): void => {
    if (type.kind === "Named") types.add(type.name);
  };
  const onExpr = (e: ExprIR): void => {
    if (e.kind === "Call" && e.callee.kind === "Function" && runtimeFunctions.has(e.callee.name)) values.add(e.callee.name);
    if ((e.kind === "Call" && e.callee.kind === "Action") || e.kind === "ActionRef") usage.store = true;
    if (e.kind === "PlainRef") usage.plain.add(e.name);
    if (e.kind === "Call" && e.callee.kind === "Plain") usage.plain.add(e.callee.name.split(".")[0]!);
  };
  const visitExpr = (expr: ExprIR): void => walkExpr(expr, onExpr);
  const visitProps = (props: readonly PropIR[]): void =>
    props.forEach((p) => {
      if (p.kind === "CallbackProp") visitFunction(p.handler);
      else visitExpr(p.value);
    });
  const visitChildren = (children: readonly ChildIR[]): void => {
    for (const child of children) {
      if (child.kind === "ChildrenSlot") continue;
      if (child.element.component.kind === "Intrinsic") values.add(child.element.component.name);
      if (child.kind === "ConditionalChild") visitExpr(child.condition);
      if (child.kind === "KeyedListChild") {
        visitExpr(child.source);
        visitExpr(child.key);
        if (child.condition) visitExpr(child.condition);
        if (child.alternate) {
          if (child.alternate.component.kind === "Intrinsic") values.add(child.alternate.component.name);
          visitProps(child.alternate.props);
          visitProps(child.alternate.transform);
        }
      }
      visitProps(child.element.props);
      visitProps(child.element.transform);
      visitChildren(child.element.children);
    }
  };
  const visitFunction = (fn: FunctionIR): void => {
    fn.params.forEach((p) => visitType(p.type));
    walkFunction(fn, onExpr, (stmt) => {
      if (stmt.kind === "CallAction") usage.store = true;
    });
  };
  if (exportedComponents(module).length > 0) types.add("PrefabDefinition");
  for (const c of module.components) {
    if (c.acceptsChildren) types.add("Child");
    values.add(c.root.component.name);
    visitProps(c.root.props);
    visitProps(c.root.transform);
    visitChildren(c.root.children);
    c.props.forEach((p) => p.defaultValue && visitExpr(p.defaultValue)); // a default may call a runtime function (`speed = clamp(5, 0, 3)`)
    c.state.forEach((s) => {
      visitExpr(s.initialValue);
      if (s.globalKey !== undefined) usage.store = true;
    });
    c.refs.forEach((r) => visitExpr(r.initialValue));
    if (c.sounds.length > 0) values.add("Sound");
    for (const hook of c.hooks) if (isHandlerHook(hook)) visitFunction(hook.handler);
    // The `onUpdate` override that calls `super` or several handlers is written with every parameter the runtime passes, `input` too.
    const updates = c.hooks.filter((h) => isHandlerHook(h) && h.kind === "OnUpdate").length;
    if ((intrinsicHooks?.[c.root.component.name] ?? []).includes("onUpdate") && updates > 0) types.add("InputState");
  }
  return [...[...values].sort(), ...[...types].sort().map((t) => `type ${t}`)];
}

/** Components imported from other source files, grouped by the specifier of their generated module (`.tsx` → `.ts`). */
function collectComponentImports(module: IRModule): Map<string, { defaultName: string | null; names: string[] }> {
  const named = new Map<string, Set<string>>();
  const defaults = new Map<string, string>();
  const visit = (children: readonly ChildIR[]): void => {
    for (const child of children) {
      if (child.kind === "ChildrenSlot") continue;
      for (const ref of [child.element.component, ...(child.kind === "KeyedListChild" && child.alternate ? [child.alternate.component] : [])]) {
        if (ref.kind === "Imported") {
          const specifier = ref.module.replace(/\.tsx$/, ".ts");
          if (!named.has(specifier)) named.set(specifier, new Set());
          if (ref.isDefault) defaults.set(specifier, ref.name);
          else named.get(specifier)!.add(ref.name);
        }
      }
      visit(child.element.children);
    }
  };
  for (const c of module.components) visit(c.root.children);
  return new Map(
    [...named]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([specifier, names]) => [specifier, { defaultName: defaults.get(specifier) ?? null, names: [...names].sort() }]),
  );
}

/** The component generator: each layer in its own file (expressions, handlers, elements), each extending the one before it. */
class ComponentGenerator extends ElementEmitter {
  emit(): void {
    const c = this.c;
    const w = this.w;
    const hasRender = this.hostHasDynamicProps() || this.childrenNeedRender(c.root.children);

    // A component with props passes them (and its defaults) up to the runtime host, which owns `this.props`.
    // `children` is not a runtime prop: the parent mounts elements at the `{children}` slot instead.
    const runtimeProps = c.propsType && c.acceptsChildren ? `Omit<${c.propsType}, "children">` : c.propsType;
    const extendsClause = runtimeProps ? `${c.root.component.name}<${runtimeProps}>` : c.root.component.name;
    w.block(`export class ${c.name} extends ${extendsClause}`, () => {
      // What a compiled component draws changes only in its constructor, its `render()` and structural changes, which the
      // runtime reports; its hooks only call setters. So the player may reuse its draw records while it stands still (see `FrameBuilder`).
      w.line("static readonly managed = true;");
      // Its `render()` writes only what differs and says what it wrote to (`markMoved`, `markChanged`), so the runtime does not
      // take every render for a change: the player keeps what it drew for a render that changed nothing, and for one that only moved it.
      w.line("protected override readonly reportsChanges = true;");
      // Its root was another component or a condition: layout sees through it to what it holds.
      if (c.root.layoutContents) w.line("override readonly layoutContents = true;");
      // Persistent state.
      for (const s of c.state) {
        if (s.globalKey !== undefined) {
          // A snapshot of the game's value (the store is the truth); refreshed in `commitState` when the leaf changes.
          w.line(`${s.name}: ${typeText(s.type)} = ${this.storeName}.store.get<${typeText(s.type)}>(${JSON.stringify(s.globalKey)});`);
          continue;
        }
        w.line(`${s.name}: ${typeText(s.type)} = ${this.expr(s.initialValue, true)};`);
        // The value setters write; it becomes `s.name` when the component next renders.
        if (this.hasSetter(s.id)) w.line(`${pending(s)}: ${typeText(s.type)} = this.${s.name};`);
      }
      // The paths it reads: the runtime tells it when one changes (see `GameObject.gameStateKeys`).
      const globals = c.state.filter((s) => s.globalKey !== undefined);
      if (globals.length > 0) {
        w.line(`override readonly gameStateStore = ${this.storeName}.store;`);
        w.line(`override readonly gameStateKeys: readonly string[] = [${[...new Set(globals.map((s) => JSON.stringify(s.globalKey)))].join(", ")}];`);
      }
      // Refs: plain fields. Reading or writing them never marks anything dirty.
      for (const r of c.refs) {
        w.line(`${r.name}: ${r.type} = ${this.expr(r.initialValue, true)};`);
      }
      // Sounds: one per useSound. Playing is an effect, so nothing is marked dirty.
      for (const s of c.sounds) {
        w.line(`readonly ${s.name}: Sound = new Sound(${JSON.stringify(s.path)});`);
      }
      // Persistent children (field initialisers run after state initialisers, so they can read state).
      this.emitElementFields(c.root.children, "persistent");

      w.blank();
      const defaults = c.props.filter((p) => p.defaultValue !== null);
      const defaultsObject = defaults.length > 0 ? `{ ${defaults.map((p) => `${propertyKey(p.name)}: ${this.expr(p.defaultValue!, true)}`).join(", ")} }` : null;
      // Every prop optional: the parent may omit the object entirely.
      const constructorParams = runtimeProps ? `props: ${runtimeProps}${c.props.every((p) => p.optional) ? " = {}" : ""}` : "";
      w.block(`constructor(${constructorParams})`, () => {
        const staticHostProps = c.root.props.filter((p) => p.kind === "StaticProp");
        // A built-in's constructor may require a prop (a Sprite's `image`) that is dynamic here. `super()` runs before
        // state exists, so it gets a placeholder and its real value in the first `render()`, which the constructor runs.
        const required = this.requiredHostProps[c.root.component.name] ?? [];
        const placeholders = c.root.props.flatMap((p) => (p.kind === "DynamicProp" && required.includes(p.name) ? [`${propertyKey(p.name)}: undefined as never`] : []));
        this.inlineMemos = true;
        const hostEntries = [...staticHostProps.map((p) => `${propertyKey(p.name)}: ${this.expr(p.value, true)}`), ...placeholders];
        this.inlineMemos = false;
        const host = hostEntries.length > 0 ? `{ ${hostEntries.join(", ")} }` : "{}";
        if (c.propsType) w.line(`super(${host}, props${defaultsObject ? `, ${defaultsObject}` : ""});`);
        else w.line(hostEntries.length > 0 ? `super(${host});` : "super();");
        // A callback on the root (`<Collider onCollisionEnter>`) is assigned after `super()`: an arrow that uses
        // `this` cannot be created inside the call to it.
        for (const p of c.root.props) {
          if (p.kind === "CallbackProp") w.line(`this.${p.name} = ${this.callback(p.handler)};`);
        }
        this.emitStaticTransform(c.root.transform, "this", "transform");
        this.emitStaticWiring(c.root.children, ROOT);
        const slot = findChildrenSlot(c.root.children, "this");
        if (slot) {
          if ("forward" in slot) {
            // The children this component is given are passed on, whole, to the component that renders them.
            w.line(`this.passedChildrenForward = ${slot.forward};`);
          } else {
            // Where a parent's children mount: the container holding `{children}`, and the slot's position among its children.
            w.line(`this.passedChildrenHost = ${slot.host};`);
            w.line(`this.passedChildrenSlot = ${slot.index};`);
          }
        }
        if (hasRender) {
          w.line("this.render();");
          w.line("this.commitStructure();");
        }
      });

      if (c.propsType) {
        w.blank();
        w.block(`updateProps(next: Partial<${runtimeProps}>): void`, () => {
          w.line(`if (this.applyProps(next${defaultsObject ? `, ${defaultsObject}` : ""})) this.markDirty();`);
        });
      }

      for (const hook of c.hooks) {
        switch (hook.kind) {
          case "UseState": {
            if (hook.setterName === null) break;
            const s = this.state(hook.state);
            const type = typeText(s.type);
            w.blank();
            // React semantics: reads see the value from the last render; updaters chain on the pending value.
            w.block(`${hook.setterName}(value: ${type} | ((previous: ${type}) => ${type})): void`, () => {
              w.line(`const next = typeof value === "function" ? value(${pendingRef(s)}) : value;`);
              w.line(`if (next === ${pendingRef(s)}) return;`);
              w.line(`${pendingRef(s)} = next;`);
              w.line("this.markDirty();");
            });
            break;
          }
          case "OnUpdate":
          case "OnInput":
          case "OnMount":
          case "OnUnmount":
            break; // emitted below, grouped by kind
          default:
            assertNever(hook, "hook");
        }
      }

      const settable = c.state.filter((s) => s.globalKey === undefined && this.hasSetter(s.id));
      const shared = c.state.filter((s) => s.globalKey !== undefined);
      if (settable.length > 0 || shared.length > 0) {
        w.blank();
        w.block("override commitState(): void", () => {
          for (const s of settable) w.line(`this.${s.name} = ${pendingRef(s)};`);
          // Every component that reads a leaf refreshes its snapshot when the game changes it, whoever acted.
          for (const s of shared) w.line(`this.${s.name} = ${this.storeName}.store.get<${typeText(s.type)}>(${JSON.stringify(s.globalKey)});`);
        });
      }

      // Hot reload: the component's own state and refs, by their stable ids, so a rebuilt tree can take them back
      // (see `captureHotState` in the runtime). A value whose type no longer matches is skipped.
      const local = c.state.filter((s) => s.globalKey === undefined);
      if (local.length > 0 || c.refs.length > 0) {
        w.blank();
        w.block("override saveHotState(): Record<string, unknown>", () => {
          const entries = [
            ...local.map((s) => `${JSON.stringify(s.id)}: ${this.hasSetter(s.id) ? pendingRef(s) : `this.${s.name}`}`),
            ...c.refs.map((r) => `${JSON.stringify(r.id)}: this.${r.name}`),
          ];
          w.line(`return { ${entries.join(", ")} };`);
        });
        w.blank();
        w.block("override loadHotState(saved: Record<string, unknown>): void", () => {
          w.line("let value: unknown;");
          for (const s of local) {
            const target = this.hasSetter(s.id) ? pendingRef(s) : `this.${s.name}`;
            w.line(`value = saved[${JSON.stringify(s.id)}];`);
            w.line(`if (this.hotFits(value, ${target})) ${target} = value as ${typeText(s.type)};`);
          }
          for (const r of c.refs) {
            w.line(`value = saved[${JSON.stringify(r.id)}];`);
            w.line(`if (this.hotFits(value, this.${r.name})) this.${r.name} = value as ${r.type};`);
          }
          // A setter's value reaches its field, and a field's value reaches what is drawn, on the next render.
          if (hasRender || settable.length > 0) w.line("this.markDirty();");
        });
      }

      this.emitHandlerMethods();

      if (hasRender) {
        w.blank();
        w.block("override render(): void", () => {
          this.renderTemps = 0;
          const dynamic = c.root.props.filter((p) => p.kind === "DynamicProp");
          this.emitReportedWrites(dynamic.map((prop) => ({ target: access("this", prop.name), value: prop.value })), "this.markChanged()");
          this.emitDynamicTransform(c.root.transform, "this", "transform");
          this.emitChildUpdates(c.root.children, ROOT, "persistent");
        });
      }
    });
  }
}
